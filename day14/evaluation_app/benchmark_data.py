BENCHMARKS = SIMPLE_FACT_CASES + PARAPHRASE_CASES + MULTI_EVIDENCE_CASES + AMBIGUOUS_CASES + UNANSWERABLE_CASES

EXPECTED_CASE_COUNTS = {
    "简单事实": 20,
    "同义改写": 10,
    "多证据": 10,
    "模糊 Query": 5,
    "不可回答": 5,
}


def validate_benchmarks(benchmarks=BENCHMARKS):
    """检查数量、ID 和可回答性相关字段是否自洽。"""
    actual_counts = Counter(case["case_type"] for case in benchmarks)
    if dict(actual_counts) != EXPECTED_CASE_COUNTS:
        raise ValueError(
            f"Benchmark 类型数量错误：{dict(actual_counts)}"
        )

    case_ids = [case["case_id"] for case in benchmarks]
    if len(case_ids) != len(set(case_ids)):
        raise ValueError("Benchmark 中存在重复 case_id。")

    for case in benchmarks:
        has_ground_truth = case["ground_truth_answer"] is not None
        has_relevant_ids = bool(case["relevant_document_ids"])
        if case["answerable"] != (has_ground_truth and has_relevant_ids):
            raise ValueError(
                f"{case['case_id']} 的 answerable、Ground Truth 或相关文档不一致。"
            )
